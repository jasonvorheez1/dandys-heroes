/* Packs the short .ogg sound effects (the ones js/audio-redirect.js serves in place of a .wav) into ONE file,
   SFX/sfx-pack.bin, and writes js/audio-pack.js with the index and the loader. The game is held on the loading screen until the
   pack has arrived (see js/item-sheet.js); each sound is then handed out as a blob URL, so no game code changes.
   Nothing is deleted by default. After checking the game with the pack in place, run with --apply to delete the loose .ogg files that are packed
   (git can bring them back). Re-run this after running tools/convert-audio.js, which regenerates the list.
   usage (from the game folder): node tools/pack-audio.js [--apply] */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const apply = process.argv.includes('--apply');
const redirect = fs.readFileSync(path.join(ROOT, 'js', 'audio-redirect.js'), 'utf8');
const wavs = JSON.parse(redirect.match(/new Set\((\[.*?\])\)/s)[1]);
const oggs = wavs.map(w => w.replace(/\.wav$/i, '.ogg')).filter(o => fs.existsSync(path.join(ROOT, o)));

if (!oggs.length) { console.log('no loose .ogg files to pack (already packed?). Nothing changed.'); process.exit(0); }
const index = {}, chunks = [];
let offset = 0;
oggs.forEach(o => {
  const data = fs.readFileSync(path.join(ROOT, o));
  index[o] = [offset, data.length];
  chunks.push(data);
  offset += data.length;
});
const PACK = 'SFX/sfx-pack.bin';
if (!apply || !fs.existsSync(path.join(ROOT, PACK))) fs.writeFileSync(path.join(ROOT, PACK), Buffer.concat(chunks));

fs.writeFileSync(path.join(ROOT, 'js', 'audio-pack.js'), `/* Generated by tools/pack-audio.js. Do not edit. One download holds the short sound effects; AudioPack.url(path) hands one out as a blob URL. */
'use strict';
(() => {
  const INDEX = ${JSON.stringify(index)};
  let buffer = null;
  const cache = {};
  window.AudioPack = {
    ready: fetch(${JSON.stringify(PACK)}).then(r => r.ok ? r.arrayBuffer() : null).then(b => { buffer = b; }).catch(() => {}),
    url(key) {
      const at = INDEX[key];
      if (!buffer || !at) return null;
      return cache[key] || (cache[key] = URL.createObjectURL(new Blob([buffer.slice(at[0], at[0] + at[1])], { type: 'audio/ogg' })));
    }
  };
})();
`);
console.log(oggs.length + ' sounds packed, ' + (offset / 1048576).toFixed(1) + ' MB into ' + PACK);

if (apply) {
  if (!fs.existsSync(path.join(ROOT, PACK))) throw new Error('pack missing');
  oggs.forEach(o => fs.unlinkSync(path.join(ROOT, o)));
  console.log('deleted ' + oggs.length + ' loose .ogg files');
}
