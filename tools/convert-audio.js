/* Converts local .wav files under SFX/ and assets/ to .ogg (Vorbis) next to the originals, then writes
   js/audio-redirect.js, which makes the browser fetch the .ogg when it can play it. The WAVs are kept as the fallback
   (and for browsers without Ogg support, such as older Safari). Safe to re-run.
   usage (from the game folder): node tools/convert-audio.js */
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const DIRS = ['SFX', 'assets'];
const wavs = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name), st = fs.statSync(full);
    if (st.isDirectory()) walk(full);
    else if (/\.wav$/i.test(name)) wavs.push(full);
  }
})(ROOT);
const local = wavs.filter(f => DIRS.includes(path.relative(ROOT, f).split(path.sep)[0]));

let made = 0, kept = 0, failed = [], before = 0, after = 0;
const list = [];
for (const wav of local) {
  const ogg = wav.replace(/\.wav$/i, '.ogg');
  if (!fs.existsSync(ogg)) {
    const r = spawnSync('ffmpeg', ['-y', '-v', 'error', '-i', wav, '-c:a', 'libvorbis', '-q:a', '4', ogg]);
    if (r.status !== 0 || !fs.existsSync(ogg) || fs.statSync(ogg).size < 100) { failed.push(wav); try { fs.unlinkSync(ogg); } catch (_) { /* none */ } continue; }
    made++;
  } else kept++;
  // an ogg that is not smaller is not worth switching to
  const w = fs.statSync(wav).size, o = fs.statSync(ogg).size;
  if (o >= w) continue;
  before += w; after += o;
  list.push(path.relative(ROOT, wav).split(path.sep).join('/'));
}

const body = `/* Generated by tools/convert-audio.js. Do not edit. Sends .wav requests for the files below to their smaller .ogg twin
   when this browser can play Ogg Vorbis; otherwise (or on any error) the original .wav is used. */
'use strict';
(() => {
  const SET = new Set(${JSON.stringify(list)});
  const probe = document.createElement('audio');
  if (!probe.canPlayType || !probe.canPlayType('audio/ogg; codecs="vorbis"')) return;
  const swap = url => {
    if (typeof url !== 'string' || !/\\.wav(\\?|$)/i.test(url) || /^(https?:)?\\/\\//i.test(url)) return url;
    let key = url.replace(/^\\.\\//, '').replace(/\\?.*$/, '');
    try { key = decodeURI(key); } catch (_) { return url; }
    return SET.has(key) ? url.replace(/\\.wav(\\?|$)/i, '.ogg$1') : url;
  };
  const NativeAudio = window.Audio;
  window.Audio = function (src) { return arguments.length ? new NativeAudio(swap(src)) : new NativeAudio(); };
  window.Audio.prototype = NativeAudio.prototype;
  const desc = Object.getOwnPropertyDescriptor(HTMLMediaElement.prototype, 'src');
  if (desc && desc.set) Object.defineProperty(HTMLMediaElement.prototype, 'src', { configurable: true, enumerable: desc.enumerable, get: desc.get, set(v) { desc.set.call(this, swap(v)); } });
  const nativeFetch = window.fetch;
  window.fetch = function (input, init) {
    if (typeof input === 'string') {
      const next = swap(input);
      if (next !== input) return nativeFetch.call(this, next, init).then(r => r.ok ? r : nativeFetch.call(this, input, init), () => nativeFetch.call(this, input, init));
    }
    return nativeFetch.apply(this, arguments);
  };
})();
`;
fs.writeFileSync(path.join(ROOT, 'js', 'audio-redirect.js'), body);
console.log(`wav found ${local.length}, new ogg ${made}, existing ${kept}, failed ${failed.length}, redirected ${list.length}`);
console.log(`wav ${(before / 1048576).toFixed(1)} MB -> ogg ${(after / 1048576).toFixed(1)} MB`);
if (failed.length) console.log('failed:\n' + failed.join('\n'));
