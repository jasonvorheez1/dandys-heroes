/* Turns the GLaDOS MUGEN sound bank into the game's sound pack: every clip as mono Ogg Vorbis, concatenated into one file
   (assets/aperture/sfx/aperture-sfx.bin) with an index (assets/aperture/sfx/index.json: name -> [offset, length, seconds]).
   Names: the effects have names read from how the MUGEN code uses them; the voice lines are named by group and number
   (taunt-12, core-1010-5, ...) because only a person who has heard them can name them. See assets/aperture/sfx/NAMES.md.
   usage: node tools/portal/build-sfx.js <GLaDOS.snd> */
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const sndFile = process.argv[2];
if (!sndFile) { console.log('usage: node build-sfx.js <GLaDOS.snd>'); process.exit(1); }
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'assets', 'aperture', 'sfx');
const TMP = path.join(require('os').tmpdir(), 'aperture-sfx');
fs.mkdirSync(OUT, { recursive: true });
fs.mkdirSync(TMP, { recursive: true });
const ext = spawnSync(process.execPath, [path.join(__dirname, 'snd-extract.js'), sndFile, path.join(TMP, 'wav')], { stdio: 'inherit' });
if (ext.status !== 0) throw new Error('extract failed');
const list = JSON.parse(fs.readFileSync(path.join(TMP, 'wav', 'sounds.json'), 'utf8'));

// group 0 are the effects. Names come from the state that plays them in the MUGEN code.
const FX = { 0: 'open', 1: 'warning', 2: 'voice-long', 3: 'clank-a', 4: 'shoot-a', 5: 'boom-a', 8: 'boom-b', 10: 'door', 12: 'boomboomboom',
  14: 'hit', 15: 'clank-b', 17: 'shoot-b', 18: 'laser', 19: 'charge', 20: 'glass-break' };
const GROUPS = { 100: 'taunt', 1000: 'core-squeal', 1010: 'core-a', 1020: 'core-b', 5000: 'voice-5000', 5050: 'cake', 5100: 'voice-5100', 10000: 'monologue', 11000: 'incinerator' };
const nameOf = s => s.group === 0 ? (FX[s.number] || 'sfx-' + s.number) : (GROUPS[s.group] || 'snd-' + s.group) + '-' + s.number;

const index = {}, chunks = [];
let offset = 0;
const names = [];
for (const s of list) {
  const wav = path.join(TMP, 'wav', s.file), ogg = path.join(TMP, s.file.replace('.wav', '.ogg'));
  const r = spawnSync('ffmpeg', ['-y', '-v', 'error', '-i', wav, '-ac', '1', '-ar', '22050', '-c:a', 'libvorbis', '-q:a', '1', ogg]);
  if (r.status !== 0 || !fs.existsSync(ogg)) { console.log('skipped ' + s.file); continue; }
  const data = fs.readFileSync(ogg), name = nameOf(s);
  index[name] = [offset, data.length, s.seconds];
  chunks.push(data); offset += data.length;
  names.push(`${name}\t${s.seconds}s\t(group ${s.group}, number ${s.number})`);
}
fs.writeFileSync(path.join(OUT, 'aperture-sfx.bin'), Buffer.concat(chunks));
fs.writeFileSync(path.join(OUT, 'index.json'), JSON.stringify(index));
fs.writeFileSync(path.join(OUT, 'NAMES.md'), `# GLaDOS sound names\n\nGenerated by tools/portal/build-sfx.js. Effects (group 0) were named from the MUGEN code that plays them. Voice lines are named by group and number only; they need a person to listen and write down what is said.\n\n\`\`\`\n${names.join('\n')}\n\`\`\`\n`);
console.log(names.length + ' sounds, ' + (offset / 1048576).toFixed(1) + ' MB');
