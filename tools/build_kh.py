"""Embed the Kingdom Hearts sources (tools/kh-src) into js/game.js."""
import json, subprocess
B = '/workspace/tools/bundle.py'; SRC = '/workspace/tools/kh-src/'
def put(name, path, where, other):
    subprocess.check_call(['python3', '-I', B, 'put', name, path, where, other])
meta = open(SRC + 'kh_meta.json').read()
open('/tmp/kh-atlas.js', 'w').write("/* kh-atlas.js - generated by tools/kh_sprites.py + tools/kh_heartless.py. */\n'use strict';\nconst KH_ATLAS = " + meta + ";\n")
put('data/kh-atlas.js', '/tmp/kh-atlas.js', '--after', 'data/ff7-materia.js')
put('data/kh-core.js', SRC + 'kh-core.js', '--after', 'data/kh-atlas.js')
put('data/kh-heroes.js', SRC + 'kh-heroes.js', '--after', 'data/kh-core.js')
put('data/kh-enemies.js', SRC + 'kh-enemies.js', '--after', 'data/kh-heroes.js')
put('meta/kh.js', SRC + 'kh-event.js', '--after', 'meta/ff7.js')
put('data/kh-story.js', SRC + 'kh-story.js', '--after', 'meta/kh.js')
put('ui/screens/kh.js', SRC + 'kh-screen.js', '--after', 'ui/screens/ff7.js')
put('ui/screens/kh-wood.js', SRC + 'kh-wood.js', '--after', 'ui/screens/kh.js')
print('built')
# ---- css
css = open('/workspace/css/styles.css', encoding='utf-8').read()
a, b = '/* KH-BEGIN */', '/* KH-END */'
block = a + '\n' + open(SRC + 'kh.css', encoding='utf-8').read() + '\n' + b
if a in css: css = css[:css.index(a)] + block + css[css.index(b) + len(b):]
else: css = css.rstrip('\n') + '\n\n' + block + '\n'
open('/workspace/css/styles.css', 'w', encoding='utf-8').write(css)
print('css done')
