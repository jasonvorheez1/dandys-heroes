/* Builds assets-manifest.json: every asset with its type, size, top-level group and whether its file name appears in the code.
   usage (from the game folder): node tools/build-manifest.js
   "referenced" is a text search of js/, css/ and index.html for the file name, so it is a hint, not proof
   (names built at runtime will show false). Never delete a file on this alone. */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SKIP = new Set(['tools', '_cleanup', 'vendor', 'node_modules', '.git', 'assets-manifest.json']);
const CODE_EXT = new Set(['.js', '.css', '.html', '.json', '.py', '.bat']);
const TYPES = { audio: ['.wav', '.mp3', '.ogg'], image: ['.png', '.webp', '.gif', '.svg', '.jpg', '.jpeg'], effect: ['.efk', '.efkefc', '.efkproj', '.efkmat'], code: ['.js', '.css', '.html'] };
const typeOf = ext => Object.keys(TYPES).find(t => TYPES[t].includes(ext)) || 'other';

const files = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    if (SKIP.has(name) && dir === ROOT) continue;
    const full = path.join(dir, name), st = fs.statSync(full);
    if (st.isDirectory()) walk(full);
    else files.push({ full, size: st.size });
  }
})(ROOT);

let code = '';
files.filter(f => CODE_EXT.has(path.extname(f.full).toLowerCase()) && f.size < 8e6 && !/assets-manifest/.test(f.full))
  .forEach(f => { code += fs.readFileSync(f.full, 'utf8') + '\n'; });

const assets = files.map(f => {
  const rel = path.relative(ROOT, f.full).split(path.sep).join('/');
  const ext = path.extname(rel).toLowerCase(), type = typeOf(ext);
  return {
    path: rel, type, ext, bytes: f.size,
    group: rel.split('/').slice(0, rel.startsWith('assets/') ? 2 : 1).join('/'),
    referenced: type === 'code' ? null : code.includes(path.basename(rel))
  };
}).sort((a, b) => a.path.localeCompare(b.path));

const summary = {};
assets.forEach(a => { const s = summary[a.type] || (summary[a.type] = { files: 0, bytes: 0 }); s.files++; s.bytes += a.bytes; });
const groups = {};
assets.forEach(a => { const g = groups[a.group] || (groups[a.group] = { files: 0, bytes: 0 }); g.files++; g.bytes += a.bytes; });

fs.writeFileSync(path.join(ROOT, 'assets-manifest.json'), JSON.stringify({
  about: 'Generated by tools/build-manifest.js. Do not edit by hand; re-run the script. See HANDOFF.md.',
  generated: new Date().toISOString().slice(0, 10), summary, groups, assets
}, null, 1));
console.log(assets.length + ' files', JSON.stringify(summary));
